const DICT: Record<Lang, Dict> = { en, hi, kn, ta, te, bn, mr };

export function t(lang: Lang, key: UiKey): string {
  return DICT[lang][key];
}

/** `/mann-ki-baat/<lang>?/path`; `en` has no prefix. */
export function localePath(lang: Lang, path: string): string {
  return `${BASE}${lang === 'en' ? '' : `/${lang}`}${path.startsWith('/') ? path : `/${path}`}`;
}

/** Localized text; machine languages fall back to English when empty. */
export function pick(b: Localized, lang: Lang): string {
  const v = b[lang];
  if (typeof v === 'string' && v.trim()) return v;
  return lang === 'en' || lang === 'hi' ? (v ?? '') : b.en;
}
